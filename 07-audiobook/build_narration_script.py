#!/usr/bin/env python3
"""Soft Life Series — narration script generator (AI narration route).

Adapts a book's manuscript into a narration script optimized for text-to-speech
production: tables and worksheets are flagged for manual adaptation, checkboxes
become spoken steps, scene breaks become pause markers, and URLs become spoken
forms where appropriate.

Usage:
  python3 build_narration_script.py <book-id>      # e.g. 01-soft-life-system
  python3 build_narration_script.py --list

Reads the book config from 06-production/books/<book-id>.toml and writes:
  07-audiobook/<book-id>/narration-script.md

The generated script is a strong v1 — hand-tune the [ADAPT] blocks before
feeding audio generation. Conventions understood by the TTS pipeline:
  [PAUSE 1s] / [PAUSE 2s]          explicit pauses
  [SECTION BREAK]                  long beat + breath
  [ADAPT MANUALLY]                 block needs human rewrite before narration
  [SKIP]                           content deliberately not narrated
"""

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOOKS = ROOT / "06-production" / "books"
AUDIO = ROOT / "07-audiobook"

WORDS_PER_HOUR = 9400  # ACX industry average for pacing ~155 wpm


def spoken_url(text: str) -> str:
    """Convert common URL/email patterns to spoken form."""
    text = text.replace("studio.gabochie.com", "studio dot gabochie dot com")
    text = text.replace("admin@gabochie.com", "admin at gabochie dot com")
    text = text.replace("@gideonabochie", "at gideon abochie")
    return text


def adapt_block(raw: str) -> str:
    out = []

    # Strip HTML comments
    raw = re.sub(r"<!--.*?-->", "", raw, flags=re.S)

    lines = raw.splitlines()
    i = 0
    table_buf = []

    def flush_table():
        nonlocal table_buf
        if table_buf:
            out.append("[ADAPT MANUALLY — TABLE]\n" + "\n".join(table_buf) + "\n[/ADAPT]")
            table_buf = []

    checkbox_count = 0
    in_code = False
    for line in lines:
        stripped = line.strip()

        if stripped.startswith("```"):
            in_code = not in_code
            flush_table()
            out.append("[ADAPT MANUALLY — CODE BLOCK]" if in_code else "[/ADAPT]")
            continue
        if in_code:
            out.append(line)
            continue

        # Tables
        if stripped.startswith("|"):
            table_buf.append(stripped)
            continue
        else:
            flush_table()

        # Front-matter contents list is skipped (book has generated TOC)
        if stripped == "## Contents":
            out.append("[SKIP — auto-generated Contents section]")
            continue

        # Headings → spoken lines (strip hashes; keep text for TTS)
        m = re.match(r"^(#{1,6})\s+(.*)$", line)
        if m:
            heading = m.group(2).strip()
            if heading:
                out.append(f"\n{spoken_url(heading)}\n")
            continue

        # Scene breaks
        if re.fullmatch(r"-{3,}", stripped):
            out.append("[PAUSE 2s]")
            continue

        # Checkboxes → spoken numbered steps
        m = re.match(r"^[-*]\s*\[([ xX])\]\s*(.*)$", line)
        if m:
            checkbox_count += 1
            state = m.group(1)
            item = m.group(2).strip()
            done = " Completed." if state in "xX" else ""
            out.append(f"{checkbox_count}. {item}{done}")
            continue

        # Regular bullets keep their dash (TTS reads list items fine)
        out.append(spoken_url(line))

    flush_table()
    return "\n".join(out)


def heading_spoken(text: str) -> str:
    """'Chapter 7: Title' heading — keep as-is; TTS engines handle ordinals."""
    return text


def chapter_num_words(n: int) -> str:
    words = ["zero", "one", "two", "three", "four", "five", "six", "seven",
             "eight", "nine", "ten", "eleven", "twelve", "thirteen", "fourteen",
             "fifteen", "sixteen", "seventeen", "eighteen", "nineteen", "twenty"]
    return words[n] if n < len(words) else str(n)


def main(book_id: str) -> None:
    cfg_path = BOOKS / f"{book_id}.toml"
    if not cfg_path.exists():
        sys.exit(f"Config not found: {cfg_path}")
    cfg = tomllib.load(open(cfg_path, "rb"))
    book = cfg["book"]
    ms = ROOT / book["manuscript_dir"]
    out_dir = AUDIO / book_id
    out_dir.mkdir(parents=True, exist_ok=True)

    title = book["title"]
    subtitle = book["subtitle"]
    author = book["author"]
    year = book["year"]

    chunks = []

    # ---- Opening credits ----
    chunks.append(f"""# {title} — Narration Script

> Generated by 07-audiobook/build_narration_script.py from the locked manuscript.
> Runtime estimate at generation time shown at the bottom. Hand-tune [ADAPT]
> blocks, then run the AI narration pipeline (see _template/ai-narration-workflow.md).

---

## OPENING CREDITS

[PAUSE 1s]

This is {title}: {subtitle}.

[NARRATOR — female mentor voice "Ava" (AI narration; see voice-spec.md)]

{title}, written by {author}. Copyright © {year} by {author}. All rights reserved.

{cfg.get("publisher", "Gabochie Books")}

[PAUSE 1s]

---

## INTRODUCTION
""")

    intro_raw = (ms / "01-introduction.md").read_text(encoding="utf-8")
    chunks.append(adapt_block(intro_raw))

    # ---- Chapters in parts order ----
    chapters = [c["file"] for c in cfg["chapters"]]
    for part in cfg["parts"]:
        chunks.append(f"\n---\n\n## {part['number'].upper()} — {part['title'].upper()}\n\n"
                      f"[SECTION BREAK]\n\n"
                      f"{part['number']}. {part['title']}.\n\n[PAUSE 1s]\n\n"
                      f"[Part subtitle, read warmly: \"{part['subtitle']}\"]\n")
        for n in range(part["start"], part["end"] + 1):
            raw = (ms / "chapters" / chapters[n - 1]).read_text(encoding="utf-8")
            first_line = raw.lstrip().splitlines()[0]
            m = re.match(r"^#\s*(.+?)\s*$", first_line)
            spoken_title = spoken_url(m.group(1).strip()) if m else f"Chapter {n}"
            # Ensure "Chapter N:" is spoken with the word number
            spoken_title = re.sub(
                r"^Chapter\s+(\d+)\b",
                lambda mm: f"Chapter {chapter_num_words(int(mm.group(1)))}",
                spoken_title,
            )
            # The chapter title is spoken in the part/chapter chunk header —
            # strip the raw markdown heading to avoid narrating it twice.
            raw = re.sub(r"^\s*#\s*Chapter[^\n]*\n", "", raw.lstrip(), count=1)
            chunks.append(f"\n---\n\n## {spoken_title.upper()}\n\n[SECTION BREAK]\n\n"
                          f"{spoken_title}.\n\n[PAUSE 1s]\n")
            chunks.append(adapt_block(raw))

    # ---- Back matter ----
    chunks.append("\n---\n\n## BACK MATTER\n\n[SECTION BREAK]\n")
    back_raw = (ms / "99-back-matter.md").read_text(encoding="utf-8")
    chunks.append(adapt_block(back_raw))

    # ---- Closing credits ----
    chunks.append(f"""
---

## CLOSING CREDITS

[PAUSE 1s]

This concludes {title}, written by {author}.

Narrated by Ava (AI narration).

[PAUSE 1s]

For the curated tools, templates, and resources mentioned in this book, visit
studio dot gabochie dot com.

[PAUSE 1s]

Thank you for listening.

[PAUSE 2s]

[END OF RECORDING — 5 seconds room tone]
""")

    script = "\n".join(chunks)

    # Stats
    spoken = re.sub(r"\[[^\]]*\]", "", script)  # exclude marker text from count
    words = len(re.findall(r"\S+", spoken))
    hours = words / WORDS_PER_HOUR

    header_note = (f"\n> **Script stats:** {words:,} spoken words · "
                   f"est. {hours:.1f} finished hours ({WORDS_PER_HOUR:,} w/h basis)\n")
    script = script.replace(
        "> blocks, then run the AI narration pipeline (see _template/ai-narration-workflow.md).",
        "> blocks, then run the AI narration pipeline (see _template/ai-narration-workflow.md)."
        + header_note,
    )

    out = out_dir / "narration-script.md"
    out.write_text(script, encoding="utf-8")
    print(f"Wrote {out}")
    print(f"  spoken words: {words:,} · est. finished runtime: {hours:.1f} hours")


def list_books() -> None:
    for p in sorted(BOOKS.glob("*.toml")):
        if p.stem != "_template":
            print(p.stem)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    if sys.argv[1] in ("-l", "--list"):
        list_books()
    else:
        main(sys.argv[1])
